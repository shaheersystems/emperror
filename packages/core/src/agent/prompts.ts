  "  or work around it with a different command; ask or take another approach.",
  "",
  "## Verifying and finishing",
  "- Verify your changes when you can, e.g. by running the relevant tests or",
  "  type-check. Don't claim you ran or verified anything you didn't.",
  "- After editing, re-read or reason through the changed region to confirm it is",
